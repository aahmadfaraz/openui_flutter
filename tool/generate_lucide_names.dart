// Regenerates lib/src/icons/lucide_names.dart from the resolved flutter_lucide
// package, so `Icon("circle-check")` in openui-lang can find its IconData.
//
// Run from the package root after bumping flutter_lucide:
//   dart run tool/generate_lucide_names.dart
import 'dart:convert';
import 'dart:io';

void main() {
  final config =
      jsonDecode(File('.dart_tool/package_config.json').readAsStringSync())
          as Map<String, dynamic>;
  final lucide = (config['packages'] as List)
      .cast<Map<String, dynamic>>()
      .firstWhere((p) => p['name'] == 'flutter_lucide');
  final root = Uri.parse(lucide['rootUri'] as String);
  final dir = root.isAbsolute
      ? root.toFilePath()
      : File('.dart_tool/${lucide['rootUri']}').absolute.path;
  final source = File('$dir/lib/src/flutter_lucide.dart').readAsStringSync();

  final names = RegExp(
    r'static const IconData ([a-z0-9_]+) =',
  ).allMatches(source).map((m) => m[1]!).toList()..sort();

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/generate_lucide_names.dart — do not edit.')
    ..writeln(
      '// ${names.length} icons from flutter_lucide, keyed by Lucide kebab-case name.',
    )
    ..writeln('// ignore_for_file: lines_longer_than_80_chars')
    ..writeln()
    ..writeln("import 'package:flutter/widgets.dart';")
    ..writeln("import 'package:flutter_lucide/flutter_lucide.dart';")
    ..writeln()
    ..writeln('const Map<String, IconData> lucideIconsByName = {');
  for (final name in names) {
    out.writeln("  '${name.replaceAll('_', '-')}': LucideIcons.$name,");
  }
  out.writeln('};');
  File('lib/src/icons/lucide_names.dart').writeAsStringSync(out.toString());
  stdout.writeln('Wrote ${names.length} icons.');
}
